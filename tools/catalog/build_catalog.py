#!/usr/bin/env python3
"""Build protocol/windows-catalog.md from the decompiled corpus. Facts only: names, routes, numbers."""
import collections, re, subprocess, sys
from pathlib import Path

root = Path("corpus/windows/decompiled"); out = Path("protocol/windows-catalog.md")
raw = subprocess.run([sys.executable, "-I", "tools/catalog/scan_windows.py", str(root)], capture_output=True, text=True).stdout
sections = collections.defaultdict(list); cur = None
for line in raw.splitlines():
    m = re.match(r"=== (\w+)", line)
    if m: cur = m.group(1); continue
    if cur and line.strip():
        key, _, src = line.strip().partition("   <- ")
        sections[cur].append((key, src))

FEATURE = [("Transport and platform (YPP)", r"YourPhone\.YPP|Connectivity"), ("Messaging", r"Messaging"), ("Photos", r"Photos"),
           ("Contacts", r"Contacts"), ("Calling", r"Calling"), ("Notifications", r"Notifications"), ("Devices and status", r"Devices|Audio|Hotspot|Help"),
           ("Shared content and file transfer", r"SharedContent"), ("Screen mirroring and app streaming", r"ScreenMirroring|AppProxy|Controls|Shell")]
groups = collections.OrderedDict((name, []) for name, _ in FEATURE); groups["Other"] = []
for route, src in sections["routes"]:
    first = src.split(",")[0]
    for name, rx in FEATURE:
        if re.search(rx, first): groups[name].append((route, src)); break
    else: groups["Other"].append((route, src))

L = ["# Phone Link for Windows: protocol catalog", "",
     "Source: `Microsoft.YourPhone` 1.26072.257.0 (arm64), decompiled with ilspycmd. Generated by",
     "`tools/catalog/build_catalog.py`. Names and numbers only; no decompiled code is reproduced here.", "",
     "## DCG REST endpoints", "", "Base URL `https://dcg.microsoft.com/` (also `dcg-df` and `dcg-beta` rings). From the generated Kiota client.", ""]
for key, _ in sections["apiver"]:
    if key.startswith("{+baseurl}"): L.append("- `" + re.sub(r"[?&]$", "", re.sub(r"\{[&?]?[^}]*\*\}", "", key.replace("{+baseurl}", "").replace("%2D", "-")).replace("Api-Version", "api-version").replace("?api-version={api-version}&", "?").replace("&api-version={api-version}", "").replace("?api-version={api-version}", "")).replace("%2D", "-") + "`")
L += ["", "## Auth scopes", ""] + [f"- `{k}`" for k, _ in sections["scopes"]] + [f"- `{k}`" for k, _ in sections["urls"] if "DCG.ReadWrite" in k and "dcg.microsoft.com" in k]
L += ["", "## Hub Relay (SignalR) methods invoked by the PC", ""] + [f"- `{k}`" for k, _ in sections["hubs"]]
L += ["", "## Routes by feature", ""]
for name, rows in groups.items():
    if not rows: continue
    L += [f"### {name} ({len(rows)})", ""] + [f"- `{r}`" for r, _ in rows] + [""]
L += ["## Recovered protobuf schemas", "", "Exact `.proto` files rebuilt from embedded descriptors, under `protocol/recovered/windows/`. All compile with `protoc`.", ""]
for p in sorted(Path("protocol/recovered/windows").rglob("*.proto")):
    text = p.read_text()
    L.append(f"- `{p.relative_to('protocol/recovered/windows')}`: {len(re.findall(r'^ *message ', text, re.M))} messages, {len(re.findall(r'^ *enum ', text, re.M))} enums")
out.write_text("\n".join(L) + "\n")
print(out, len(L), "lines;", {k: len(v) for k, v in groups.items()})
